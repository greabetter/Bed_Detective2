static void touch_test(void)
{
    LOG("=== I2C scan ===\r\n");
    for (uint8_t a = 0x08; a < 0x78; a++) {
        if (HAL_I2C_IsDeviceReady(&hi2c1, a << 1, 2, 10) == HAL_OK) {
            LOG("  found 0x%02X\r\n", a);
        }
    }

    LOG("=== touch init ===\r\n");
    if (!ft6336_init()) {
        LOG("  FAIL\r\n");
        return;
    }
    LOG("  OK\r\n");

    LOG("=== read 5s, touch the screen ===\r\n");
    for (int i = 0; i < 50; i++) {
        uint16_t x, y;
        if (ft6336_read(&x, &y)) {
            LOG("  x=%d y=%d\r\n", x, y);
        }
        osDelay(100);
    }
}
